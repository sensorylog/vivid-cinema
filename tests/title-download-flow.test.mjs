import test from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";

test("title download action opens the native Vivid Offline library", async () => {
  const script = await readFile(new URL("../scripts/title.js", import.meta.url), "utf8");
  const main = await readFile(new URL("../desktop/main.cjs", import.meta.url), "utf8");
  const preload = await readFile(new URL("../desktop/preload.cjs", import.meta.url), "utf8");
  const engine = await readFile(new URL("../desktop/download-engine.cjs", import.meta.url), "utf8");
  const offline = await readFile(new URL("../scripts/downloads/desktop-offline.js", import.meta.url), "utf8");
  const page = await readFile(new URL("../my-downloads.html", import.meta.url), "utf8");
  const shell = await readFile(new URL("../scripts/app-shell.js", import.meta.url), "utf8");
  assert.match(script, /id="title-download"/);
  assert.match(script, /vivid:pending-desktop-download/);
  assert.match(script, /currentDetails\?\.seasons/);
  assert.match(script, /my-downloads\.html/);
  assert.doesNotMatch(script, /function openTitleDownload\(\)[\s\S]*?vivid-download-modal/);
  assert.match(preload, /exposeInMainWorld\("vividDownloads"/);
  assert.match(preload, /mediaUrl:.*fileIndex/);
  assert.match(preload, /getPlaybackPosition/);
  assert.match(preload, /setPlaybackPosition/);
  assert.match(preload, /addEventListener\("offline"/);
  assert.match(main, /configureDownloadEngine\(\)/);
  assert.match(main, /vivid-download-media-url/);
  assert.match(main, /vivid-playback-position-get/);
  assert.match(main, /vivid-media/);
  assert.match(main, /protocol\.handle\("vivid-media"/);
  assert.match(main, /Readable\.toWeb/);
  assert.match(main, /Accept-Ranges/);
  assert.match(main, /net\.isOnline\(\)/);
  assert.match(engine, /TorrentSearchApi\.enablePublicProviders/);
  assert.match(engine, /new WebTorrent\(\)/);
  assert.doesNotMatch(engine, /uploadLimit:\s*0/);
  assert.match(engine, /this\.client\.add\(job\.magnet, \{ path: jobPath, uploads: 0 \}\)/);
  assert.match(engine, /vivid-downloads\.json/);
  assert.match(engine, /destroyStore: false/);
  assert.match(engine, /action === "resume"/);
  assert.match(engine, /rescanFiles/);
  assert.match(engine, /job\.files/);
  assert.match(engine, /episodeTitle: safeText\(media\.episodeTitle, 180\)/);
  assert.match(offline, /episodeTitle:result\.episodeTitle/);
  assert.match(offline, /job\.title\+episodeTag/);
  assert.match(engine, /needsRescan/);
  assert.match(engine, /playbackPositions/);
  assert.match(offline, /desktop-search-form/);
  assert.match(offline, /loadSeriesSeason/);
  assert.match(offline, /searchSelectedEpisodes/);
  assert.match(offline, /S\"\+String\(season\)\.padStart\(2,"0"\)\+"E\"/);
  assert.match(page, /desktop-series-picker/);
  assert.match(page, /desktop-season-select/);
  assert.match(page, /desktop-episodes/);
  assert.match(shell, /page === "home" && !window\.vividDownloads\?\.available/);
  assert.match(shell, /navLink\("search\.html", "bi-search", "Search"/);
  assert.match(offline, /engine\.mediaUrl\(job\.id,fileIndex\)/);
  assert.match(offline, /data-action="pause"/);
  assert.match(offline, /data-action="resume"/);
  assert.match(offline, /offline-play-toggle/);
  assert.match(offline, /offline-seek/);
  assert.match(offline, /offline-fullscreen/);
  assert.match(offline, /offline-speed/);
  assert.match(offline, /play-file/);
  assert.match(offline, /engine\.getPlaybackPosition/);
  assert.match(offline, /engine\.setPlaybackPosition/);
  assert.match(page, /desktop-search-form/);
  assert.match(page, /offline-player/);
  assert.doesNotMatch(script, /Internet Archive|archive\.org|Wikimedia|wikimedia\.org/i);
});
